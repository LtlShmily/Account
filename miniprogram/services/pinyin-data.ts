export function pinyinForHanzi(character: string): string {
  const codePoint = character.codePointAt(0)
  if (codePoint === undefined || codePoint < HAN_START || codePoint > HAN_END) return ''
  const offset = (codePoint - HAN_START) * 2
  const high = INDEX_ALPHABET.indexOf(SYLLABLE_INDEX_DATA[offset])
  const low = INDEX_ALPHABET.indexOf(SYLLABLE_INDEX_DATA[offset + 1])
  if (high < 0 || low < 0) return ''
  return SYLLABLES[high * 64 + low] || ''
}
